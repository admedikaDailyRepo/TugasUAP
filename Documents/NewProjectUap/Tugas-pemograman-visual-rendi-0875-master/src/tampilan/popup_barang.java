protected void datatable(){

    Object[] Baris = {"Kode Barang","Nama Barang","Jenis","Harga Beli","Harga Jual"};

    tabmode = new DefaultTableModel(null, Baris);

    String cariitem = txtcari.getText();

    try {

        String sql = "SELECT * FROM barang where nm_brg like '%"+cariitem+"%' or nm_brg like '%"+cariitem+"%' order by nm_brg asc";

        java.sql.Statement stat = conn.createStatement();

        ResultSet hasil = stat.executeQuery(sql);

        while (hasil.next()){
            tabmode.addRow(new Object[]{
                hasil.getString(1),
                hasil.getString(2),
                hasil.getString(3),
                hasil.getString(4),
                hasil.getString(5)
            });
        }

        tblbarang.setModel(tabmode);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Gagal memuat data barang: " + e.getMessage());
        e.printStackTrace();
    }
}
